// Embed public/ into the Worker bundle (src/static-assets.js) — the UI is only a few small files.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const types = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8' };
const files = {};
for (const f of readdirSync('public')) {
  const ext = f.slice(f.lastIndexOf('.'));
  if (types[ext]) files[`/${f}`] = { type: types[ext], body: readFileSync(`public/${f}`, 'utf8') };
}
files['/'] = files['/index.html'];
files['/quote'] = files['/quote.html'];
writeFileSync('src/static-assets.js', `// Generated by scripts/build-static.js — do not edit.\nexport default ${JSON.stringify(files)};\n`);
console.log(`embedded ${Object.keys(files).length - 1} files`);
