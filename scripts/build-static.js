// Embed public/ into the Worker bundle (src/static-assets.js) — the UI and fonts are small.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const types = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.woff2': 'font/woff2' };
const files = {};
for (const f of readdirSync('public', { recursive: true })) {
  const ext = f.slice(f.lastIndexOf('.'));
  if (!types[ext]) continue;
  const binary = ext === '.woff2';
  files[`/${f}`] = { type: types[ext], binary, body: readFileSync(`public/${f}`, binary ? 'base64' : 'utf8') };
}
files['/'] = files['/index.html'];
files['/quote'] = files['/quote.html'];
files['/portal'] = files['/portal.html'];
writeFileSync('src/static-assets.js', `// Generated by scripts/build-static.js — do not edit.\nexport default ${JSON.stringify(files)};\n`);
console.log(`embedded ${Object.keys(files).length - 3} files`);
