// Generates docs/WORKFLOWS.md from public/workflows.js — the master runbook for every service.
// Safe to hand to any AI agent: it contains no client data (placeholders only).
import { writeFileSync } from 'node:fs';
import { buildRunbook } from '../src/runbook.js';
import { WORKFLOW_DEFS } from '../public/workflows.js';

const md = buildRunbook(Object.keys(WORKFLOW_DEFS)).replace('# Setup runbook', '# Service workflows — master runbook\n\n_Generated by `npm run docs:workflows` from `public/workflows.js`. Per-client runbooks (with progress flags) download from the Clients zone._');
writeFileSync('docs/WORKFLOWS.md', md);
console.log(`wrote docs/WORKFLOWS.md (${Object.keys(WORKFLOW_DEFS).length} workflows)`);
